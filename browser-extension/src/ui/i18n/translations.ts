export type TranslationKey = keyof typeof EN_US;

export function tr(locale: ExtensionLocale | string | undefined, key: TranslationKey): string {
  const norm = normalizeExtensionLocale(locale);
  const dict = norm === 'zh-CN' ? ZH_CN : EN_US;
  const val = dict[key] ?? EN_US[key];
  return typeof val === 'string' && val.length > 0 ? val : String(key);
}
